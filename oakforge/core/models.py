"""Shared data structures used by the procedural tree tools."""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any

import numpy as np


@dataclass
class Branch:
    """A branch represented by a sampled centreline and a radius profile."""

    branch_id: str
    parent_id: str | None
    role: str
    depth: int
    points: list[np.ndarray]
    radii: list[float]
    metadata: dict[str, Any] = field(default_factory=dict)

    @property
    def length(self) -> float:
        """Return the length measured along the sampled centreline."""
        return float(sum(np.linalg.norm(self.points[index + 1] - self.points[index])
                         for index in range(len(self.points) - 1)))

    def point_at(self, proportion: float) -> np.ndarray:
        """Find a position by distance along the branch, not by point index."""
        proportion = float(np.clip(proportion, 0.0, 1.0))
        segment_lengths = [np.linalg.norm(self.points[index + 1] - self.points[index])
                           for index in range(len(self.points) - 1)]
        total_length = sum(segment_lengths)
        if total_length <= 1e-8:
            return self.points[0].copy()
        target_distance = total_length * proportion
        travelled = 0.0
        for index, segment_length in enumerate(segment_lengths):
            if travelled + segment_length >= target_distance:
                local_amount = (target_distance - travelled) / max(segment_length, 1e-8)
                return self.points[index] * (1.0 - local_amount) + self.points[index + 1] * local_amount
            travelled += segment_length
        return self.points[-1].copy()

    def tangent_at(self, proportion: float) -> np.ndarray:
        """Return the local growth direction at a proportional position."""
        proportion = float(np.clip(proportion, 0.0, 1.0))
        index = min(int(proportion * (len(self.points) - 1)), len(self.points) - 2)
        direction = self.points[index + 1] - self.points[index]
        magnitude = np.linalg.norm(direction)
        return direction / magnitude if magnitude > 1e-8 else np.array([0.0, 1.0, 0.0])

    def radius_at(self, proportion: float) -> float:
        """Interpolate the branch radius along its centreline."""
        position = float(np.clip(proportion, 0.0, 1.0)) * (len(self.radii) - 1)
        lower_index = int(position)
        upper_index = min(lower_index + 1, len(self.radii) - 1)
        blend = position - lower_index
        return float(self.radii[lower_index] * (1.0 - blend) + self.radii[upper_index] * blend)


@dataclass
class Leaf:
    """An oak leaf whose outline is generated by the foliage geometry tool."""

    leaf_id: str
    base_position: np.ndarray
    growth_direction: np.ndarray
    width_direction: np.ndarray
    length: float
    width: float
    colour_variation: np.ndarray = field(default_factory=lambda: np.zeros(3, dtype=np.float64))


@dataclass
class TreeModel:
    """The generated tree, independent of any particular rendering API."""

    name: str
    branches: list[Branch]
    leaves: list[Leaf]
    metadata: dict[str, Any] = field(default_factory=dict)
